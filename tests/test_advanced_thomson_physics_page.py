def test_dashboard_routes_conditional_multi_ion_cts_flow_inference():
    from tis.ui.advanced_thomson_physics_page import EXAMPLES, MODEL_LABELS
    from tokamak_analysis.cts_full_physics import run_advanced_thomson_physics

    model = "cts_multi_ion_flow_inference"
    assert model in MODEL_LABELS
    assert model in EXAMPLES
    config = dict(EXAMPLES[model])
    # The dashboard example is a schema template. Use a spectrum generated by
    # the same public forward physics so this test verifies the real route.
    from tokamak_analysis.cts_analysis import cts_spectral_density
    frequency = np.unique(np.r_[np.linspace(-7.0e9, -0.8e9, 60), np.linspace(-0.8e9, 0.8e9, 401), np.linspace(0.8e9, 7.0e9, 60)])
    config["frequency_shift_Hz"] = frequency.tolist()
    config["instrument_response"] = np.eye(frequency.size).tolist()
    physical = cts_spectral_density(
        frequency, config["probe_frequency_Hz"], config["scattering_geometry"],
        electron_density_m3=config["electron_density_m3"],
        electron_temperature_eV=config["electron_temperature_eV"],
        ion_temperature_eV=config["ion_temperature_eV"],
        ion_species=config["ion_species"], ion_fractions=config["ion_fractions"],
        electron_velocity_projection_m_s=config["electron_velocity_projection_m_s"],
        ion_velocity_projection_m_s=config["ion_velocity_initial_m_s"],
    )
    config["measured_spectrum"] = (2.4e4 * physical + 3.0).tolist()
    config["signal_uncertainty"] = np.full(frequency.size, 0.01*np.max(config["measured_spectrum"])).tolist()
    result = run_advanced_thomson_physics(model, **config)
    assert result["public_physics_entrypoint"] == model
    assert result["model"] == "unmagnetized_electrostatic_multi_ion_maxwellian_cts"
    assert result["reportable_as_inferred_parameter"] is True

    from pathlib import Path
    root = Path(__file__).resolve().parents[1]
    formula = json.loads((root / "FORMULA_REGISTRY.json").read_text(encoding="utf-8"))
    packaged = json.loads((root / "tis" / "data" / "FORMULA_REGISTRY.json").read_text(encoding="utf-8"))
    matches = [item for item in formula if item.get("execution_contract", {}).get("formula_key") == "cts_species_resolved_ion_flow_inference"]
    assert len(matches) == 1
    assert matches[0]["execution_contract"]["function_link"] == "tokamak_analysis.cts_analysis.fit_cts_ion_species_flows"
    assert formula == packaged


